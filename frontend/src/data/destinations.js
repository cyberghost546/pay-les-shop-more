// src/data/destinations.js
//
// One entry per island the site ships to. The header dropdown, the
// /destinations index, the /destinations/:slug page, the services page and the
// homepage route map all read from here, so adding an island is a single edit.
//
// `transitDays`, `port` and `flights` describe the real service and are shown
// to customers, so they are worth keeping accurate. `mapX`/`mapY` are
// positions in the homepage map's 900×470 drawing — a schematic, not real
// coordinates.
//
//   transitDays  days at sea by sea freight. Customs clearance on the island
//                comes on top: about a week and a half.
//   flights      the air freight departures, each the key of a sentence in
//                home.map.flights that gives the latest time to hand the
//                shipment in and the day it flies. Clearance takes about
//                3-4 days.

// `hero` is an object, not a URL: src, srcSet, a small variant for CSS
// backgrounds, and the intrinsic size. Generated by `npm run images` from the
// photographs in src/images, so the originals stay the masters and the sizes
// actually served are WebP.
import {
  arubaCentraal,
  bonaireCentraal,
  curacaoCentraal,
} from '../images/optimized/photos';

// `flagMap` is the island drawn in its own flag, on a transparent ground. A
// flat-colour graphic rather than a photograph, so it is imported straight
// from src/images the way the flags are, not put through `npm run images`:
// re-encoding a drawing as WebP does not make it smaller.
//
// Every island has one. The services page still falls back to the hero
// photograph for an island without one, so adding a destination before its
// drawing exists leaves a mixed grid rather than a hole.
import arubaFlagMap from '../images/Flag_map_of_Aruba.webp';
import bonaireFlagMap from '../images/Flag_map_of_Bonaire.png';
import curacaoFlagMap from '../images/Flag_map_of_Curacao.webp';

export const DESTINATIONS = [
  {
    slug: 'aruba',
    nameKey: 'destinations.aruba',
    hero: arubaCentraal,
    flagMap: arubaFlagMap,
    port: 'Oranjestad',
    transitDays: 16,
    flights: ['thursdayWeekend'],
    mapX: 208,
    mapY: 292,
  },
  {
    slug: 'bonaire',
    nameKey: 'destinations.bonaire',
    hero: bonaireCentraal,
    flagMap: bonaireFlagMap,
    port: 'Kralendijk',
    transitDays: 18,
    flights: ['thursdayWeekend'],
    mapX: 258,
    mapY: 318,
  },
  {
    slug: 'curacao',
    nameKey: 'destinations.curacao',
    hero: curacaoCentraal,
    flagMap: curacaoFlagMap,
    port: 'Willemstad',
    transitDays: 17,
    flights: ['thursdayWeekend', 'mondayWednesday'],
    mapX: 232,
    mapY: 300,
  },
];

export function findDestination(slug) {
  return DESTINATIONS.find((item) => item.slug === slug);
}
