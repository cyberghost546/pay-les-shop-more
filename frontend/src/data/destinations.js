// src/data/destinations.js
//
// One entry per island the site ships to. The header dropdown, the
// /destinations index, the /destinations/:slug page, the services page and the
// homepage route map all read from here, so adding an island is a single edit.
//
// `transitDays` and `port` describe the real service and are shown to
// customers, so they are worth keeping accurate. `mapX`/`mapY` are positions
// in the homepage map's 900×470 drawing — a schematic, not real coordinates.

// `hero` is an object, not a URL: src, srcSet, a small variant for CSS
// backgrounds, and the intrinsic size. Generated by `npm run images` from the
// photographs in src/images, so the originals stay the masters and the sizes
// actually served are WebP.
import {
  arubaCentraal,
  bonaireCentraal,
  curacaoCentraal,
  stMaartenCentraal,
  surinameCentraal,
} from '../images/optimized/photos';

// `flagMap` is the island drawn in its own flag, on a transparent ground. A
// flat-colour graphic rather than a photograph, so it is imported straight
// from src/images the way the flags are, not put through `npm run images`:
// re-encoding a drawing as WebP does not make it smaller.
//
// Every island has one. The services page still falls back to the hero
// photograph for an island without one, so adding a destination before its
// drawing exists leaves a mixed grid rather than a hole.
import arubaFlagMap from '../images/Flag_map_of_Aruba.webp';
